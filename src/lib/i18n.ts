export const dictionaries:Record<Locale,Record<Key,string>>={de,en};
export type TFunction=(key:Key,params?:Record<string,string|number>)=>string;

export function translate(locale:Locale,key:Key,params?:Record<string,string|number>):string{
  let s=dictionaries[locale][key]??dictionaries[defaultLocale][key]??key;
  if(params)for(const [k,v] of Object.entries(params))s=s.replaceAll(`{${k}}`,String(v));
  return s;
}

