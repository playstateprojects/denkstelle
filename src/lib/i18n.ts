export type Locale=(typeof locales)[number];
export const defaultLocale:Locale='de';
export const isLocale=(x:unknown):x is Locale=>locales.includes(x as Locale);

/** Pick a locale from a cookie value, falling back to Accept-Language, then German. */
export function detectLocale(cookie:string|undefined,acceptLanguage:string|null):Locale{
  if(isLocale(cookie))return cookie;
  for(const part of (acceptLanguage??'').split(',')){
    const tag=part.trim().slice(0,2).toLowerCase();
    if(isLocale(tag))return tag;
  }
  return defaultLocale;
}

